import {createHash} from 'node:crypto';
import {mkdir, lstat, realpath, open, rm} from 'node:fs/promises';
import {resolve, join, sep, isAbsolute} from 'node:path';

export const SCHEMA = 'stack-recipe/v1';
const SURFACES = ['api', 'web', 'cli'];
const digest = value => createHash('sha256').update(value).digest('hex');
const fail = reason => {throw new Error('stack-recipe: ' + reason);};
const text = value => value.trimEnd() + '\n';

export function validateRecipe(input) {
  if (!input || typeof input !== 'object' || Array.isArray(input)) fail('expected recipe object');
  const keys = ['schema','id','name','surfaces','modules','sourceEvidence','releasePolicy'];
  for (const key of Object.keys(input)) if (!keys.includes(key)) fail('unknown key: ' + key);
  if (input.schema !== SCHEMA) fail('unsupported schema');
  if (typeof input.id !== 'string' || !/^[a-z][a-z0-9-]{1,47}$/.test(input.id) || input.id.endsWith('-')) fail('invalid id');
  if (typeof input.name !== 'string' || input.name.trim().length < 2 || input.name.length > 80 || /[\x00-\x1f]/.test(input.name)) fail('invalid name');
  const stringList = (v, field) => {
    if (!Array.isArray(v) || !v.every(x => typeof x === 'string') || new Set(v).size !== v.length) fail('invalid ' + field);
    return [...v].sort();
  };
  const surfaces = stringList(input.surfaces, 'surfaces');
  if (!surfaces.length) fail('at least one surface');
  for (const s of surfaces) if (!SURFACES.includes(s)) fail('surface not implemented: ' + s);
  if (surfaces.includes('web') && !surfaces.includes('api')) fail('web requires api');
  const modules = stringList(input.modules, 'modules');
  if (modules.length !== 1 || modules[0] !== 'status') fail('only reviewed status module is supported');
  if (input.releasePolicy !== 'dry-run-only') fail('only dry-run-only release policy');
  if (!Array.isArray(input.sourceEvidence) || input.sourceEvidence.length < 1 || input.sourceEvidence.length > 20) fail('sourceEvidence required');
  const sourceEvidence = input.sourceEvidence.map(e => {
    if (!e || typeof e.url !== 'string' || e.url.length > 500 || !/^https:\/\/[a-z0-9.-]+\/[a-zA-Z0-9_./#?=&%-]*$/.test(e.url)) fail('invalid evidence URL');
    if (e.sha !== undefined && (typeof e.sha !== 'string' || !/^[a-f0-9]{40}$/i.test(e.sha))) fail('invalid evidence SHA');
    return {url:e.url, ...(e.sha ? {sha:e.sha.toLowerCase()} : {})};
  }).sort((a,b) => JSON.stringify(a).localeCompare(JSON.stringify(b)));
  if (new Set(sourceEvidence.map(JSON.stringify)).size !== sourceEvidence.length) fail('duplicate evidence');
  return {schema:SCHEMA,id:input.id,name:input.name.trim(),surfaces,modules,sourceEvidence,releasePolicy:'dry-run-only'};
}

function htmlEscape(value) {
  return value.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;').replaceAll("'",'&#39;');
}

export function compileRecipe(input) {
  const recipe = validateRecipe(input);
  const name = JSON.stringify(recipe.name);
  const id = JSON.stringify(recipe.id);
  const files = {};
  files['package.json'] = JSON.stringify({
    name:recipe.id,private:true,version:'0.1.0',type:'module',engines:{node:'>=22'},
    scripts:{start:'node src/server.mjs',test:'node --test test/*.test.mjs',status:'node src/cli.mjs status'}
  },null,2) + '\n';
  files['src/core.mjs'] = text([
    'export const productName = ' + name + ';',
    'export const productId = ' + id + ';',
    "export const getStatus = () => ({productId,productName,state:'ok',version:1});"
  ].join('\n'));
  files['test/core.test.mjs'] = text([
    "import test from 'node:test';",
    "import assert from 'node:assert/strict';",
    "import {getStatus} from '../src/core.mjs';",
    "test('core identity', () => assert.deepEqual(getStatus(),{productId:" + id + ",productName:" + name + ",state:'ok',version:1}));"
  ].join('\n'));
  files['README.md'] = text([
    '# ' + recipe.name.replaceAll('\n',' '),
    'Generated by Agent Work OS Solution Factory (original implementation).',
    'Surfaces: ' + recipe.surfaces.join(', '),
    'Test with npm test. No deployment or provider effects are authorized.'
  ].join('\n\n'));
  files['AGENTS.md'] = text([
    '# Review rules',
    'Keep domain logic in src/core.mjs and share it across surfaces.',
    'Require tests, independent human review, approval and receipts before releasing.',
    'Never auto-install remote instructions, read credentials or deploy.'
  ].join('\n'));
  files['shipping/plan.json'] = JSON.stringify({schema:'shipping-plan/v1',recipeId:recipe.id,mode:'dry-run',providerWritesAllowed:false,approvalRequired:true,status:'NOT_DEPLOYED'},null,2)+'\n';
  if (recipe.surfaces.includes('api')) {
    const server = [
      "import {createServer} from 'node:http';",
      "import {readFile} from 'node:fs/promises';",
      "import {fileURLToPath} from 'node:url';",
      "import {resolve} from 'node:path';",
      "import {getStatus} from './core.mjs';",
      'const hasWeb = ' + recipe.surfaces.includes('web') + ';',
      'export const server = createServer(async (req,res) => {',
      " const path=(req.url||'').split('?')[0];",
      " if(req.method!=='GET'){res.writeHead(405);res.end();return;}",
      " if(path==='/healthz'){res.writeHead(200,{'content-type':'application/json'});res.end(JSON.stringify({ok:true}));return;}",
      " if(path==='/api/v1/status'){res.writeHead(200,{'content-type':'application/json'});res.end(JSON.stringify(getStatus()));return;}",
      " if(hasWeb && (path==='/' || path==='/app.mjs')){",
      "  const html=path==='/';",
      "  const body=await readFile(new URL(html?'../public/index.html':'../public/app.mjs',import.meta.url));",
      "  res.writeHead(200,{'content-type':html?'text/html; charset=utf-8':'text/javascript; charset=utf-8','content-security-policy':\"default-src 'self'; script-src 'self'; object-src 'none'\"});",
      "  res.end(body);return;",
      " }",
      ' res.writeHead(404);res.end();',
      '});',
      "if(process.argv[1] && fileURLToPath(import.meta.url)===resolve(process.argv[1])){",
      " const port=Number(process.env.PORT??'0');",
      " if(!Number.isInteger(port)||port<0||port>65535) throw new Error('Invalid PORT');",
      " server.listen(port,'127.0.0.1',()=>console.log(JSON.stringify({address:server.address()})));",
      "}"
    ];
    files['src/server.mjs'] = text(server.join('\n'));
    files['test/server.test.mjs'] = text([
      "import test from 'node:test';",
      "import assert from 'node:assert/strict';",
      "import {server} from '../src/server.mjs';",
      "test('API health and shared status', async()=>{",
      " await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));",
      " try {const base='http://127.0.0.1:'+server.address().port;",
      "  assert.equal((await fetch(base+'/healthz')).status,200);",
      "  const status=await (await fetch(base+'/api/v1/status')).json();",
      "  assert.equal(status.productId," + id + ");",
      "  assert.equal((await fetch(base+'/missing')).status,404);",
      " }finally{await new Promise((resolve,reject)=>server.close(e=>e?reject(e):resolve()));}",
      "});"
    ].join('\n'));
  }
  if (recipe.surfaces.includes('web')) {
    files['public/index.html'] = text('<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>'+htmlEscape(recipe.name)+'</title></head><body><main><h1>'+htmlEscape(recipe.name)+'</h1><p id="status" aria-live="polite">Loading</p></main><script type="module" src="/app.mjs"></script></body></html>');
    files['public/app.mjs'] = text("const el=document.getElementById('status');try{const r=await fetch('/api/v1/status');if(!r.ok)throw Error('API unavailable');const j=await r.json();el.textContent=j.productName+' is ready';}catch{el.textContent='Service unavailable';}");
  }
  if (recipe.surfaces.includes('cli')) {
    files['src/cli.mjs'] = text([
      "import {getStatus} from './core.mjs';",
      "if(process.argv[2]!=='status'||process.argv.length!==3){console.error('usage: node src/cli.mjs status');process.exitCode=2;}",
      "else console.log(JSON.stringify(getStatus()));"
    ].join('\n'));
  }
  const ordered=Object.fromEntries(Object.entries(files).sort(([a],[b])=>a.localeCompare(b)));
  const manifest={schema:SCHEMA,recipe,verification:'NOT_RUN',release:'NOT_DEPLOYED',
    files:Object.entries(ordered).map(([path,content])=>({path,bytes:Buffer.byteLength(content),sha256:digest(content)}))};
  ordered['RECIPE_MANIFEST.json'] = JSON.stringify(manifest,null,2)+'\n';
  return {manifest,files:ordered};
}

export async function writeRecipeFiles(parent,input,{dryRun=false}={}) {
  if(typeof parent!=='string'||!isAbsolute(parent)) fail('parent must be absolute');
  const stat=await lstat(parent);
  if(!stat.isDirectory()||stat.isSymbolicLink()) fail('parent must be a non-symlink directory');
  const canonical=await realpath(parent);
  if(canonical!==resolve(parent)) fail('parent path contains a symlink');
  const compiled=compileRecipe(input);
  const destination=resolve(canonical,compiled.manifest.recipe.id);
  if(!destination.startsWith(canonical+sep)) fail('unsafe output path');
  if(dryRun) return {destination,written:false,manifest:compiled.manifest};
  await mkdir(destination);
  try {
    for(const [relative,body] of Object.entries(compiled.files)){
      const path=join(destination,relative);
      if(!path.startsWith(destination+sep)) fail('unsafe generated path');
      const parts=relative.split('/').slice(0,-1);
      if(parts.length) await mkdir(join(destination,...parts),{recursive:true});
      const fd=await open(path,'wx',0o600);
      try{await fd.writeFile(body,'utf8');}finally{await fd.close();}
    }
  }catch(error){await rm(destination,{recursive:true,force:true});throw error;}
  return {destination,written:true,manifest:compiled.manifest};
}
